n1 = int(input('Digite um valor: '))
n2 = int(input('Digite outro valor: '))
s = n1 + n2
m = n1 * n2
d = n1 / n2
di = n1 // n2
e = n1 ** n2
r = n1 % n2
print('Soma: {}'.format(s))
print('Produto: {}'.format(m))
print('Potêncialização: {}'.format(e))
print('Divisão: {:.2f}'.format(d))
print('Divisão Inteira: {}'.format(di))
print('Resto da Divisão: {}'.format(r))
